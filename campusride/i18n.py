def get_language():
    return session.get("language", "en")


def translate(text):
    text = str(text)
    if get_language() == "zh":
        if text.startswith("Schedule conflict with trip #"):
            return "时间冲突：" + text.removeprefix("Schedule conflict with trip #").replace(
                "(", "（", 1
            ).replace(").", "）。", 1)
        return ZH_TRANSLATIONS.get(text, text)
    return EN_TRANSLATIONS.get(text, text)
